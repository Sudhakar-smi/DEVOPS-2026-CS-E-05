// --- EVENT MONITORING ---

export const getAllEventsAdmin = async (req, res, next) => {
  try {
    const events = await Event.find()
      .populate('organizerId', 'name email organization')
      .sort({ createdAt: -1 });

    const enriched = await Promise.all(
      events.map(async (e) => {
        const attendeeCount = await Attendee.countDocuments({ eventId: e._id, status: { $ne: 'cancelled' } });
        return {
          ...e.toObject(),
          registeredAttendees: attendeeCount
        };
      })
    );

    res.status(200).json({
      success: true,
      count: enriched.length,
      data: enriched
    });
  } catch (error) {
    next(error);
  }
};

